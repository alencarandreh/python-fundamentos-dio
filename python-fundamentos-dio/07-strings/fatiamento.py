nome = "André Luís Silva Alencar"


#TÉCNICAS DE FATIAMENTO EM PYTHON

print(nome[0]) #imprime o caractere 0 (primeiro)
print(nome[-1]) #imprime o caractere -1 (último)
print(nome[:5]) #imprime do caractere 0 até o 4 (o índice 5 não entra)
print(nome[10:]) #imprime do caractere 10 até o final
print(nome[10:16]) #imprime do caractere 10 até o 15 (o índice 16 não entra)
print(nome[10:16:2]) #pula de 2 em 2
print(nome[:]) #imprime a string inteira
print(nome[::-1]) #imprime a string de trás para frente